package com.example.livoxscanner

import java.io.File
import java.io.FileOutputStream
import java.nio.ByteBuffer
import java.nio.ByteOrder

object PlyBinaryExporter {
    private const val BYTES_PER_VERTEX = 16
    private const val CHUNK_VERTICES = 4096

    fun exportBinaryPly(file: File, points: List<ColoredPoint3D>): Long {
        val startTime = System.currentTimeMillis()
        val header = buildString {
            append("ply\n")
            append("format binary_little_endian 1.0\n")
            append("comment Generated by Livox Mid-40 Android 6DoF Scanner\n")
            append("element vertex ${points.size}\n")
            append("property float x\n")
            append("property float y\n")
            append("property float z\n")
            append("property uchar red\n")
            append("property uchar green\n")
            append("property uchar blue\n")
            append("property uchar intensity\n")
            append("end_header\n")
        }

        FileOutputStream(file).use { fos ->
            val channel = fos.channel
            channel.write(ByteBuffer.wrap(header.toByteArray(Charsets.US_ASCII)))
            val buffer = ByteBuffer
                .allocateDirect(CHUNK_VERTICES * BYTES_PER_VERTEX)
                .order(ByteOrder.LITTLE_ENDIAN)

            for (p in points) {
                if (buffer.remaining() < BYTES_PER_VERTEX) {
                    buffer.flip()
                    while (buffer.hasRemaining()) channel.write(buffer)
                    buffer.clear()
                }
                buffer.putFloat(p.x)
                buffer.putFloat(p.y)
                buffer.putFloat(p.z)
                buffer.put(p.r.toByte())
                buffer.put(p.g.toByte())
                buffer.put(p.b.toByte())
                buffer.put(p.reflectivity.toByte())
            }
            if (buffer.position() > 0) {
                buffer.flip()
                while (buffer.hasRemaining()) channel.write(buffer)
            }
        }
        return System.currentTimeMillis() - startTime
    }
}
